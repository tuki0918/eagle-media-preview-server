type IconName = keyof typeof lucideIcons;

export function renderLucideIcons(root: ParentNode = document) {
  for (const placeholder of root.querySelectorAll<HTMLElement>("[data-lucide]")) {
    const name = placeholder.dataset.lucide as IconName;
    const paths = lucideIcons[name];
    if (!paths) continue;
    const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    svg.setAttribute("viewBox", "0 0 24 24");
    svg.setAttribute("aria-hidden", "true");
    svg.innerHTML = paths;
    placeholder.replaceWith(svg);
  }
}

export function iconNode(name: IconName) {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("aria-hidden", "true");
  svg.innerHTML = lucideIcons[name] || "";
  return svg;
}
